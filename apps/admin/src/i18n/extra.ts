const CATALOGS: Record<Locale, Record<string, string>> = { es, en };

export type ExtraKey = keyof typeof es;

/** Traduce contra el catálogo local y cae a `@psp/i18n`, luego a la propia clave. */
export function t(locale: Locale, key: string, params?: MessageParams): string {
  const local = CATALOGS[locale]?.[key] ?? CATALOGS.es[key];
  if (local !== undefined) return interpolate(local, params);
  return baseT(locale, key, params);
}

export interface Translator {
  readonly locale: Locale;
  t: (key: string, params?: MessageParams) => string;
  tl: (text: LocalizedText | undefined, fallback?: string) => string;
  formatMoney: (money: Money) => string;
  formatNumber: (n: number, options?: Intl.NumberFormatOptions) => string;
  formatDuration: (seconds: number) => string;
  formatDate: (iso: string, timezone: string, style?: 'short' | 'long') => string;
  formatTime: (iso: string, timezone: string) => string;
}

/** Traductor ligado a un idioma, listo para pasar a pantallas y componentes. */
export function createTranslator(locale: Locale): Translator {
  return {
    locale,
    t: (key, params) => t(locale, key, params),
    tl: (text, fallback) => tl(locale, text, fallback),
    formatMoney: (money) => baseFormatMoney(money, locale),
    formatNumber: (n, options) => baseFormatNumber(n, locale, options),
    formatDuration: (seconds) => baseFormatDuration(seconds, locale),
    formatDate: (iso, timezone, style) => baseFormatDate(iso, locale, timezone, style),
    formatTime: (iso, timezone) => baseFormatTime(iso, locale, timezone),
  };
}

